FIXTURE_DIR = Path(__file__).resolve().parent / 'fixtures' / 'legacy_e90e3b1'
FIXTURE_SHA256 = {
    'queue-registry.sqlite3': '20fa659160feb837508f4bc56b8195360a7bcf0c241c66d2294f04474aeb6fbc',
    'rows.json': 'd717b3705394740f7c418ae61f827267dd2cd1a35c054b9330bc08b3cf47dd65',
    'generate.py': '071e529faa0bfca8a332ed450d0b4c866d1affc9f9690d7c85d39786773e4523',
}
DIGEST = 'a' * 64
RUN_FOLDER_SUFFIX = '/.runtime/project-a/runs/'
PROJECT = 'project-a'
ENV_OVERRIDES = ('HERDR_QUEUE_ALLOW_REFUSED', 'HERDR_QUEUE_FORCE', 'HERDR_QUEUE_OVERRIDE', 'HERDR_MIGRATE_FORCE')


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def fixture_rows():
    return json.loads((FIXTURE_DIR / 'rows.json').read_text())


class LegacyFixtureTests(unittest.TestCase):
    """Shared setup: a private copy of the fixture store, re-rooted to a temporary project layout."""

    def setUp(self):
        temp = tempfile.TemporaryDirectory(prefix='p7w2-test-')
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name).resolve()
        os.chmod(self.root, 0o700)
        self.home = self.root / 'home'
        self.home.mkdir(mode=0o700)
        self.store = self.home / '.local' / 'state' / 'herdr-ml' / 'queue-registry.sqlite3'
        self.store.parent.mkdir(parents=True, mode=0o700)
        self.folders = {}
        for run in ('run-1', 'run-2', 'run-3'):
            folder = self.root / '.runtime' / PROJECT / 'runs' / run
            folder.mkdir(parents=True, mode=0o700)
            self.folders[run] = folder

    def materialize(self):
        """Copy the fixture bytes into the private store and re-root its run folders (copy only)."""
        for name, digest in FIXTURE_SHA256.items():
            self.assertEqual(sha256(FIXTURE_DIR / name), digest, 'fixture %s changed' % name)
        shutil.copyfile(FIXTURE_DIR / 'queue-registry.sqlite3', self.store)
        os.chmod(self.store, 0o600)
        # The first open by current code adds the queue_submitters table (an additive schema
        # step that every open performs). Do it once here so the byte checks below measure
        # only the fence and the refusals.
        registry._queue_connect(self.folders['run-1'], self.home).close()
        original_base = None
        for row in fixture_rows()['queue_binding']:
            if row['run_folder'].endswith(RUN_FOLDER_SUFFIX + row['run_id']):
                original_base = row['run_folder'][:-len(RUN_FOLDER_SUFFIX + row['run_id'])]
        self.assertIsNotNone(original_base)
        db = sqlite3.connect(str(self.store))
        try:
            with db:
                for run, folder in self.folders.items():
                    db.execute('UPDATE queue_binding SET run_folder=? WHERE run_id=?',
                               (str(folder.resolve()), run))
        finally:
            db.close()
        return self.snapshot()

    def snapshot(self):
        return self.store.read_bytes()

    def row(self, run):
        return registry.inspect_queue(self.folders[run], _store_home=self.home)

    def events(self, run):
        db = sqlite3.connect(str(self.store))
        try:
            return [phase for (phase,) in db.execute(
                'SELECT phase FROM queue_events WHERE run_id=? ORDER BY seq', (run,)).fetchall()]
        finally:
            db.close()

    def set_detail(self, run, phase, detail):
        db = sqlite3.connect(str(self.store))
        try:
            with db:
                db.execute('UPDATE queue_events SET detail=? WHERE seq = ('
                           'SELECT seq FROM queue_events WHERE run_id=? AND phase=? LIMIT 1)',
                           (detail, run, phase))
        finally:
            db.close()


class StubDaemon:
    """Answers like a daemon that holds the fixture's tasks; records every client call."""

    def __init__(self, instance, tasks):
        self.instance = instance
        self.tasks = tasks
        self.calls = []

    def instance_id(self):
        return self.instance

    def status(self):
        self.calls.append(('status',))
        return {'tasks': self.tasks}

    def client(self, *args, **kwargs):
        self.calls.append(args)
        raise AssertionError('no client call is allowed for a fenced historical row: %r' % (args,))


class FixtureProvenanceTests(unittest.TestCase):
    def test_fixture_bytes_match_the_recorded_hashes(self):
        for name, digest in FIXTURE_SHA256.items():
            self.assertEqual(sha256(FIXTURE_DIR / name), digest, name)

    def test_fixture_records_the_refusal_and_the_replay_it_allowed(self):
        data = fixture_rows()
        events = {}
        for event in data['queue_events']:
            events.setdefault(event['run_id'], []).append(event['phase'])
        self.assertEqual(events['run-1'], ['INTENT', 'BOUND', 'ENQUEUE_ATTEMPTED', 'ENQUEUE_REFUSED'])
        self.assertEqual(events['run-2'], ['INTENT', 'BOUND', 'ENQUEUE_ATTEMPTED', 'ENQUEUE_REFUSED',
                                           'ENQUEUE_ATTEMPTED', 'ENQUEUED'])
        self.assertEqual(events['run-3'][-2:], ['ENQUEUE_REFUSED', 'CLAIMED'])
        phases = {row['run_id']: row['phase'] for row in data['queue_binding']}
        self.assertEqual(phases, {'run-1': 'BOUND', 'run-2': 'BOUND', 'run-3': 'CLAIMED'})
        self.assertEqual(data['daemon_task_states_at_generation']['1']['Done']['result'], 'Success')


class LegacyRefusalFenceTests(LegacyFixtureTests):
    def test_refused_bound_row_cannot_be_released_and_is_fenced(self):
        self.materialize()
        before = self.snapshot()
        row = self.row('run-1')
        self.assertEqual(row['phase'], 'BOUND')
        daemon = StubDaemon(row['queue_instance'], {row['task_id']: {
            'label': qa.task_label('run-1', row['intent_token']), 'status': 'Stashed'}})
        with self.assertRaisesRegex(registry.RegistryError, 'REGISTRY_UNREADABLE|fenced') as ctx:
            qa.release(daemon, self.folders['run-1'], _store_home=self.home)
        self.assertNotIn('REGISTRY_UNREADABLE', str(ctx.exception))
        self.assertEqual(daemon.calls, [('status',)], 'no enqueue may reach the daemon')
        after = self.row('run-1')
        self.assertEqual((after['phase'], after['ambiguous_from'], after['task_id']),
                         ('AMBIGUOUS', 'BOUND', row['task_id']))
        self.assertEqual(self.events('run-1')[-2:], ['AMBIGUOUS', 'LEGACY_REFUSED_FENCED'])
        self.assertNotEqual(self.snapshot(), before, 'the fence is a committed write')
        # The fence is final: a second release attempt is refused without a daemon call.
        with self.assertRaises(qa.QueueAdapterError):
            qa.release(daemon, self.folders['run-1'], _store_home=self.home)
        self.assertEqual(daemon.calls, [('status',)], 'a fenced row never reaches the daemon again')

    def test_direct_registry_enqueue_attempt_is_refused_on_fenced_row(self):
        self.materialize()
        row = self.row('run-2')
        with self.assertRaisesRegex(registry.RegistryError, 'fenced'):
            registry.queue_enqueue_attempted(self.folders['run-2'], row['intent_token'], _store_home=self.home)
        self.assertEqual(self.row('run-2')['phase'], 'AMBIGUOUS')
        self.assertNotIn('ENQUEUE_ATTEMPTED', self.events('run-2')[-1:])

    def test_reconcile_on_refused_row_reads_daemon_and_never_enqueues(self):
        self.materialize()
        row = self.row('run-1')
        daemon = StubDaemon(row['queue_instance'], {row['task_id']: {
            'label': qa.task_label('run-1', row['intent_token']), 'status': 'Stashed'}})
        report = qa.reconcile(daemon, self.folders['run-1'], _store_home=self.home)
        self.assertEqual(report['phase'], 'AMBIGUOUS')
        self.assertTrue(all(call == ('status',) for call in daemon.calls))
        self.assertEqual(self.row('run-1')['ambiguous_from'], 'BOUND')

    def test_claim_of_refused_bound_row_is_refused_and_fenced(self):
        self.materialize()
        row = self.row('run-1')
        with self.assertRaisesRegex(registry.RegistryError, 'fenced'):
            registry.queue_claim(self.folders['run-1'], 'run-1', DIGEST, row['queue_instance'],
                                 row['task_id'], 'worker-1', _store_home=self.home)
        self.assertEqual(self.row('run-1')['phase'], 'AMBIGUOUS')
        self.assertIsNone(self.row('run-1')['worker_id'])

    def test_idempotent_claim_of_refused_bound_row_is_refused_and_fenced(self):
        self.materialize()
        row = self.row('run-1')
        with self.assertRaisesRegex(registry.RegistryError, 'fenced'):
            registry.queue_claim_idempotent(self.folders['run-1'], 'run-1', DIGEST, row['queue_instance'],
                                            row['task_id'], 'worker-1', _store_home=self.home)
        self.assertEqual(self.row('run-1')['phase'], 'AMBIGUOUS')
        self.assertIsNone(self.row('run-1')['worker_id'])

    def test_recovery_fences_refused_row_without_resubmission(self):
        self.materialize()
        self.assertEqual(registry.queue_recover(self.folders['run-2'], _store_home=self.home), 'AMBIGUOUS')
        self.assertEqual(self.row('run-2')['ambiguous_from'], 'BOUND')

    def test_claimed_row_keeps_its_owner_and_is_not_rewritten(self):
        self.materialize()
        before = self.row('run-3')
        before_events = self.events('run-3')
        report = registry.queue_migrate_legacy_refusals(self.folders['run-3'], _store_home=self.home)
        self.assertEqual(report, {'run-1': 'FENCED', 'run-2': 'FENCED', 'run-3': 'KEPT'})
        self.assertEqual(self.row('run-3'), before)
        self.assertEqual(self.events('run-3'), before_events)


class MigrationReconciliationTests(LegacyFixtureTests):
    def test_first_run_fences_every_refused_bound_row_in_one_transaction(self):
        self.materialize()
        report = registry.queue_migrate_legacy_refusals(self.folders['run-1'], _store_home=self.home)
        self.assertEqual(report, {'run-1': 'FENCED', 'run-2': 'FENCED', 'run-3': 'KEPT'})
        for run in ('run-1', 'run-2'):
            row = self.row(run)
            self.assertEqual((row['phase'], row['ambiguous_from']), ('AMBIGUOUS', 'BOUND'))
            self.assertEqual(self.events(run)[-2:], ['AMBIGUOUS', 'LEGACY_REFUSED_FENCED'])
        self.assertEqual(self.row('run-3')['phase'], 'CLAIMED')

    def test_second_run_changes_no_bytes(self):
        self.materialize()
        registry.queue_migrate_legacy_refusals(self.folders['run-1'], _store_home=self.home)
        once = self.snapshot()
        report = registry.queue_migrate_legacy_refusals(self.folders['run-1'], _store_home=self.home)
        self.assertEqual(report, {'run-1': 'ALREADY_FENCED', 'run-2': 'ALREADY_FENCED', 'run-3': 'KEPT'})
        self.assertEqual(hashlib.sha256(self.snapshot()).digest(), hashlib.sha256(once).digest())
        self.assertEqual(self.snapshot(), once)

    def test_interrupted_migration_commits_no_fence_and_no_marker(self):
        self.materialize()
        before = self.snapshot()
        real_event = registry._queue_event
        calls = []

        def interrupt_after_fence(db, run_id, phase, detail):
            calls.append(phase)
            if phase == registry.LEGACY_FENCE_MARKER:
                raise RuntimeError('power loss between fence and marker')
            return real_event(db, run_id, phase, detail)

        with patch.object(registry, '_queue_event', interrupt_after_fence):
            with self.assertRaises(RuntimeError):
                registry.queue_migrate_legacy_refusals(self.folders['run-1'], _store_home=self.home)
        self.assertIn('AMBIGUOUS', calls)
        self.assertEqual(self.snapshot(), before, 'rollback must leave the store bytes unchanged')
        self.assertEqual(self.row('run-1')['phase'], 'BOUND')
        # The interrupted run did not open a replay: the next enqueue attempt is still fenced.
        with self.assertRaisesRegex(registry.RegistryError, 'fenced'):
            registry.queue_enqueue_attempted(self.folders['run-1'], self.row('run-1')['intent_token'],
                                             _store_home=self.home)
        self.assertEqual(self.row('run-1')['phase'], 'AMBIGUOUS')

    def test_existing_legitimate_records_are_not_overwritten(self):
        self.materialize()
        legit_folder = self.root / '.runtime' / PROJECT / 'runs' / 'run-legit'
        legit_folder.mkdir(parents=True)
        instance = self.row('run-1')['queue_instance']
        token = registry.queue_intent(legit_folder, 'run-legit', DIGEST, instance, _store_home=self.home)
        registry.queue_bind_task(legit_folder, token, '9', _store_home=self.home)
        registry.queue_enqueue_attempted(legit_folder, token, _store_home=self.home)
        registry.queue_enqueue_outcome(legit_folder, token, 'ENQUEUED', _store_home=self.home)
        legit_before = registry.inspect_queue(legit_folder, _store_home=self.home)
        legit_events = self.events('run-legit')
        registry.queue_migrate_legacy_refusals(self.folders['run-1'], _store_home=self.home)
        self.assertEqual(registry.inspect_queue(legit_folder, _store_home=self.home), legit_before)
        self.assertEqual(self.events('run-legit'), legit_events)
        self.assertEqual(legit_before['phase'], 'BOUND')

    def test_damaged_refusal_event_stays_blocked_and_bytes_are_unchanged(self):
        self.materialize()
        self.set_detail('run-1', 'ENQUEUE_REFUSED', '{not json')
        before = self.snapshot()
        with self.assertRaisesRegex(registry.RegistryError, 'REGISTRY_UNREADABLE'):
            registry.queue_migrate_legacy_refusals(self.folders['run-1'], _store_home=self.home)
        self.assertEqual(self.snapshot(), before)
        with self.assertRaisesRegex(registry.RegistryError, 'REGISTRY_UNREADABLE'):
            registry.queue_enqueue_attempted(self.folders['run-1'], self.row('run-1')['intent_token'],
                                             _store_home=self.home)
        self.assertEqual(self.snapshot(), before)
        self.assertEqual(self.row('run-1')['phase'], 'BOUND')

    def test_refusal_history_on_a_non_bound_non_claimed_row_stays_blocked(self):
        self.materialize()
        db = sqlite3.connect(str(self.store))
        try:
            with db:
                db.execute("UPDATE queue_binding SET phase='RETRYABLE' WHERE run_id='run-2'")
        finally:
            db.close()
        before = self.snapshot()
        with self.assertRaisesRegex(registry.RegistryError, 'REGISTRY_UNREADABLE'):
            registry.queue_migrate_legacy_refusals(self.folders['run-1'], _store_home=self.home)
        self.assertEqual(self.snapshot(), before)

    def test_truncated_store_is_refused_as_unreadable_and_never_repaired(self):
        self.materialize()
        data = self.store.read_bytes()
        self.store.write_bytes(data[: len(data) // 2])
        before = self.snapshot()
        with self.assertRaisesRegex(registry.RegistryError, 'REGISTRY_UNREADABLE'):
            registry.queue_migrate_legacy_refusals(self.folders['run-1'], _store_home=self.home)
        self.assertEqual(self.snapshot(), before)

    def test_refused_outcome_cannot_be_recorded_as_a_new_enqueue_result(self):
        self.materialize()
        before = self.snapshot()
        with self.assertRaisesRegex(registry.RegistryError, 'Unknown enqueue outcome'):
            registry.queue_enqueue_outcome(self.folders['run-1'], self.row('run-1')['intent_token'],
                                           'ENQUEUE_REFUSED', 'exit 1', _store_home=self.home)
        self.assertEqual(self.snapshot(), before)


class NoOverrideTests(LegacyFixtureTests):
    def test_no_environment_variable_lifts_the_fence(self):
        self.materialize()
        before = {k: os.environ.get(k) for k in ENV_OVERRIDES}
        with patch.dict(os.environ, {k: '1' for k in ENV_OVERRIDES}):
            with self.assertRaises(registry.RegistryError):
                registry.queue_enqueue_attempted(self.folders['run-1'], self.row('run-1')['intent_token'],
                                                 _store_home=self.home)
            registry.queue_migrate_legacy_refusals(self.folders['run-1'], _store_home=self.home)
            self.assertEqual(self.row('run-1')['phase'], 'AMBIGUOUS')
        self.assertEqual({k: os.environ.get(k) for k in ENV_OVERRIDES}, before)

    def test_no_entry_point_accepts_an_override_parameter(self):
        names = set()
        for func in (registry.queue_enqueue_attempted, registry.queue_claim, registry.queue_claim_idempotent,
                     registry.queue_recover, registry.queue_migrate_legacy_refusals,
                     qa.release, qa.reconcile, qa.verify_callback):
            names.update(inspect.signature(func).parameters)
        for forbidden in ('force', 'override', 'allow', 'skip', 'ignore', 'unfence', 'migrate_flag'):
            self.assertFalse(any(forbidden in name for name in names), forbidden)


