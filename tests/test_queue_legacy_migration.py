"""P7.1: historical ENQUEUE_REFUSED rows are fenced AMBIGUOUS, never replayed.

The fixture tests/fixtures/legacy_e90e3b1/queue-registry.sqlite3 was generated by the
e90e3b1 code against a private pinned Pueue daemon (see that directory's README and
generate.py). Tests copy it into a temporary store, re-root its run folders to the test
layout, and never write to the fixture itself. Offline: no daemon is started here.
"""
